"""A map of each document: its parts, what each says, and what the whole is about.

Why it exists
-------------
The private RAG answers one question well: *which passages are closest to this
sentence?* On 2026-09-29 a teacher attached a 222-page book and asked for "a
lesson on personal finance for my class". The search did its job -- the 8
passages closest to that sentence, out of 297 -- and the Writer, handed under 3 %
of a book it knew nothing else about, wrote its usual lesson from the Knowledge
Graph and cited the book zero times. Nothing in 8 fragments says what a book is
about, how it is organised, or which chapter holds the idea worth teaching; and
nothing in a similarity search can answer "what are the key ideas?", because no
single passage contains the answer (the same wall the survey queries hit on
2026-09-24).

The map is that missing overview, built once when the document is indexed:

* **the parts** -- the PDF's own table of contents when it has one (books do),
  else its headings, else windows of pages -- each with its pages and the range
  of indexed passages it spans, so a search can later be sent *into* a part;
* **one short summary per part** and a handful of key concepts, from the vision
  model already used for OCR (cheap: a 344-page book is a few cents);
* **a summary of the whole** and its main themes, from the part summaries.

The Writer reads the map to know what the document holds; the search uses it to
reach the parts a request is about. The map is *orientation*, generated by a
model: it is never cited. Citations stay on the passages, which are the
document's own words.

Failures are not the document's failure: without a map the document is still
indexed and searchable exactly as before (see ``ExtractionHandler``).
"""

from __future__ import annotations

import asyncio
import io
import json
import logging
import math
import os
import re
from dataclasses import dataclass
from typing import Any, Optional

logger = logging.getLogger(__name__)

#: A change to how parts are cut or summarised is a new map version; maps of an
#: older version are ignored rather than mixed.
MAP_VERSION = "map@1"

DEFAULT_MODEL = "google/gemini-3.5-flash-lite"

#: Below this, a document is one part: a handout does not need a table of
#: contents, and splitting it would only cost calls.
WHOLE_DOCUMENT_CHARS = 8_000

#: A book's outline can run to hundreds of entries. Beyond this many parts the
#: map stops being an overview, and the calls add up.
MAX_SECTIONS = 30

#: Parts shorter than this (a copyright page, a dedication) are folded into a
#: neighbour instead of getting a summary of their own.
MIN_SECTION_CHARS = 1_500

#: How much of a part the model reads. A 20-page chapter is ~60 000 characters;
#: an even sample of it says what the chapter is about at a fraction of the cost.
SECTION_SAMPLE_CHARS = 12_000

#: Concurrent calls while mapping one document. The worker handles one document
#: at a time; this only overlaps the waits on the provider.
CONCURRENCY = 4


def map_enabled() -> bool:
    """On with the private RAG unless switched off: the text already leaves the
    machine for the embeddings, under the same zero-retention terms."""
    from aix.webui.materials.embedding import private_rag_enabled

    flag = (os.getenv("AIX_DOCUMENT_MAP_ENABLED") or "true").strip().lower()
    return private_rag_enabled() and flag not in ("0", "false", "no", "off")


def map_model() -> str:
    return (os.getenv("AIX_DOCUMENT_MAP_MODEL") or DEFAULT_MODEL).strip()


# ---------------------------------------------------------------------------
# The parts
# ---------------------------------------------------------------------------


@dataclass
class Part:
    title: str
    #: Indices into ``ir.blocks``, inclusive.
    first: int
    last: int
    source: str  # outline | chapters | headings | window | whole


def _block_chars(blocks, first: int, last: int) -> int:
    return sum(len(blocks[i].text or "") for i in range(first, last + 1))


def _pdf_outline(content: Optional[bytes]) -> list[tuple[str, int, int]]:
    """``(title, first page, depth)`` from the PDF's bookmarks, in page order."""
    if not content:
        return []
    try:
        from pypdf import PdfReader

        reader = PdfReader(io.BytesIO(content))
        if reader.is_encrypted:
            reader.decrypt("")
        entries: list[tuple[str, int, int]] = []

        def walk(items, depth: int) -> None:
            for item in items:
                if isinstance(item, list):
                    walk(item, depth + 1)
                    continue
                try:
                    page = reader.get_destination_page_number(item) + 1
                except Exception:  # noqa: BLE001 — a broken bookmark is skipped
                    continue
                title = " ".join(str(getattr(item, "title", "") or "").split())
                if title:
                    entries.append((title, page, depth))

        walk(reader.outline, 0)
        return sorted(entries, key=lambda e: (e[1], e[2]))
    except Exception:  # noqa: BLE001 — no outline is a normal case
        logger.debug("[document-map] no usable outline", exc_info=True)
        return []


def _parts_from_starts(blocks, starts: list[tuple[str, int]], source: str) -> list[Part]:
    """Block indices where parts begin -> parts covering every block once."""
    starts = sorted({index: title for title, index in starts}.items())
    if not starts or starts[0][0] != 0:
        starts = [(0, "Inizio")] + starts
    parts = []
    for n, (index, title) in enumerate(starts):
        last = starts[n + 1][0] - 1 if n + 1 < len(starts) else len(blocks) - 1
        if last >= index:
            parts.append(Part(title=title, first=index, last=last, source=source))
    return parts


def _from_outline(blocks, outline: list[tuple[str, int, int]]) -> list[Part]:
    for depth in (1, 0):  # chapters and sections, or chapters alone if too many
        entries = [(t, p) for t, p, d in outline if d <= depth]
        if 2 <= len(entries) <= MAX_SECTIONS * 2:
            starts = []
            for title, page in entries:
                index = next(
                    (i for i, b in enumerate(blocks) if b.page is not None and b.page >= page),
                    None,
                )
                if index is not None:
                    starts.append((title, index))
            if len(starts) >= 2:
                return _parts_from_starts(blocks, starts, "outline")
    return []


#: A line that opens a chapter in most books, in the languages teachers use.
_CHAPTER_LINE = re.compile(
    r"^\s*(chapter|capitolo|cap\.|part|parte|unit|unità|unita|lezione|lesson|modulo|"
    r"module|sezione|section|chapitre|kapitel|capítulo|capitulo)\s+([0-9]{1,3}|[ivxlc]{1,7})\b"
    r"[\s.:–—-]*(.*)$",
    re.I,
)


def _from_chapter_lines(blocks) -> list[Part]:
    """«Chapter 3» at the top of a block. A PDF split in two, or exported without
    bookmarks, keeps its chapter openings in the text (2026-09-29: a 222-page
    book, cut in halves, had lost its outline but not its «Chapter 1..6»)."""
    starts = []
    for i, b in enumerate(blocks):
        first = (b.text or "").strip().split("\n")[0]
        match = _CHAPTER_LINE.match(first) if len(first) <= 80 else None
        if not match:
            continue
        title = " ".join(first.split())
        if not match.group(3).strip():
            # «Chapter 1» alone on its line: the title is usually the next line.
            following = ((b.text or "").strip().split("\n") + [""])[1].strip()
            if not following and i + 1 < len(blocks):
                following = (blocks[i + 1].text or "").strip().split("\n")[0]
            if following and len(following) <= 100:
                title += " — " + " ".join(following.split())
        starts.append((title[:120], i))
    return _parts_from_starts(blocks, starts, "chapters") if len(starts) >= 2 else []


def _from_headings(blocks) -> list[Part]:
    starts = [
        (" ".join(b.text.split())[:120], i)
        for i, b in enumerate(blocks)
        if b.kind == "heading" and (b.level or 1) <= 2 and (b.text or "").strip()
    ]
    return _parts_from_starts(blocks, starts, "headings") if len(starts) >= 2 else []


def _windows(blocks, page_count: Optional[int]) -> list[Part]:
    """Equal stretches of pages, or of text when there are no pages."""
    if page_count and any(b.page is not None for b in blocks):
        size = max(6, math.ceil(page_count / MAX_SECTIONS))
        starts, seen = [], set()
        for i, b in enumerate(blocks):
            if b.page is None:
                continue
            window = (b.page - 1) // size
            if window not in seen:
                seen.add(window)
                first = window * size + 1
                starts.append((f"pp. {first}–{min(first + size - 1, page_count)}", i))
        return _parts_from_starts(blocks, starts, "window")

    total = _block_chars(blocks, 0, len(blocks) - 1)
    size = max(15_000, math.ceil(total / MAX_SECTIONS))
    starts, running = [], 0
    for i, b in enumerate(blocks):
        if running == 0 or running >= size:
            starts.append((f"parte {len(starts) + 1}", i))
            running = 0
        running += len(b.text or "")
    return _parts_from_starts(blocks, starts, "window")


def _fold_small(blocks, parts: list[Part]) -> list[Part]:
    """Fold tiny parts into the next one, then cap the count by merging pairs."""
    folded: list[Part] = []
    carry: Optional[Part] = None
    for part in parts:
        if carry is not None:
            part = Part(title=part.title, first=carry.first, last=part.last, source=part.source)
            carry = None
        if (
            _block_chars(blocks, part.first, part.last) < MIN_SECTION_CHARS
            and part is not parts[-1]
        ):
            carry = part
            continue
        folded.append(part)
    if carry is not None and folded:
        folded[-1].last = carry.last
    elif carry is not None:
        folded.append(carry)

    while len(folded) > MAX_SECTIONS:
        merged = []
        for n in range(0, len(folded), 2):
            pair = folded[n : n + 2]
            merged.append(
                Part(
                    title=" · ".join(p.title for p in pair),
                    first=pair[0].first,
                    last=pair[-1].last,
                    source=pair[0].source,
                )
            )
        folded = merged
    return folded


def plan_parts(ir, content: Optional[bytes] = None) -> list[Part]:
    """Cut the document into the parts a teacher would name."""
    blocks = [b for b in ir.blocks if (b.text or "").strip() or b.rows]
    if not blocks:
        return []
    total = _block_chars(blocks, 0, len(blocks) - 1)
    if total < WHOLE_DOCUMENT_CHARS:
        return [Part(title="Documento", first=0, last=len(blocks) - 1, source="whole")]

    parts = []
    if ir.media_type == "application/pdf":
        parts = _from_outline(blocks, _pdf_outline(content))
    if not parts and not ir.media_type.endswith("presentationml.presentation"):
        parts = _from_chapter_lines(blocks) or _from_headings(blocks)
    if not parts:
        parts = _windows(blocks, ir.page_count)
    return _fold_small(blocks, parts)


def _sample(blocks, part: Part, budget: int = SECTION_SAMPLE_CHARS) -> str:
    """The part's text, or an even sample of it: beginning, middle and end all
    speak, instead of the first pages alone."""
    texts = [" ".join((blocks[i].text or "").split()) for i in range(part.first, part.last + 1)]
    whole = "\n".join(t for t in texts if t)
    if len(whole) <= budget:
        return whole
    windows = 6
    size = budget // windows
    stride = (len(whole) - size) / (windows - 1)
    return "\n[…]\n".join(whole[int(k * stride) : int(k * stride) + size] for k in range(windows))


