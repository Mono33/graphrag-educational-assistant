#!/usr/bin/env python3
"""Write deploy/.env.local for the local rehearsal of the production stack.

The base is ``.env.prod.example`` -- what the VM will be configured from -- so
the rehearsal runs the production settings, not the developer's. On top of it:

* the **secrets** from the repository's ``.env``: API keys, Neo4j, Langfuse;
* the **pilot settings**, the ones validated in development: the private-material
  flags on, reuse of the graph corpus on follow-up turns, the writer's token
  budget and model;
* what a laptop needs instead of a domain: plain-HTTP cookies, a local origin,
  a fresh session secret and a random database password.

Nothing is printed but the names of the keys that were set, never a value.
``.env.local`` is git-ignored (deploy/.gitignore).

Usage, from deploy/::

    python make_local_env.py
"""

from __future__ import annotations

import secrets
import sys
from pathlib import Path

DEPLOY = Path(__file__).resolve().parent
EXAMPLE = DEPLOY / ".env.prod.example"
DEV_ENV = DEPLOY.parent / ".env"
OUT = DEPLOY / ".env.local"

#: Taken from the developer's .env when present: credentials, and nothing else.
SECRETS = (
    "OPENROUTER_API_KEY",
    "OPENAI_API_KEY",
    "NEO4J_URI",
    "NEO4J_USER",
    "NEO4J_PASSWORD",
    "NEO4J_ENCRYPTED",
    "LANGFUSE_PUBLIC_KEY",
    "LANGFUSE_SECRET_KEY",
    "LANGFUSE_BASE_URL",
    "YOUTUBE_API_KEY",
)

#: The pilot's configuration. Since 2026-10-05 it is also the code's default
#: (parser, materials, private RAG, conditional retrieval, light turns, vision
#: OCR, tracing, live media): written out anyway, so that a rehearsal stays the
#: pilot even if a default changes again.
PILOT = {
    "AIX_UPLOAD_PARSER_ENABLED": "true",
    "AIX_MATERIALS_ENABLED": "true",
    "AIX_PRIVATE_RAG_ENABLED": "true",
    "AIX_CONDITIONAL_RETRIEVAL_ENABLED": "true",
    "AIX_LIGHT_TURNS_ENABLED": "true",
    "AIX_WRITER_MAX_TOKENS": "8000",
    "AIX_OCR_BACKEND": "vision",
    "AIX_TRACING_ENABLED": "true",
}

#: Taken from the developer's .env as well, because they are what the tests of
#: the last weeks ran against, and they differ from the example.
FROM_DEV = ("LLM_MODEL",)

LOCAL = {
    "AIX_DOMAIN": "localhost",
    "AIX_TLS_EMAIL": "rehearsal@localhost",
    "ENVIRONMENT": "rehearsal",
    # Secure cookies are never sent over plain HTTP: login would silently fail.
    "WEBUI_COOKIE_SECURE": "0",
    "WEBUI_CORS_ALLOW_ORIGINS": "http://127.0.0.1:8766",
    "GIT_SHA": "local",
}


def read(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


def main() -> int:
    if not EXAMPLE.exists() or not DEV_ENV.exists():
        print(f"missing {EXAMPLE if not EXAMPLE.exists() else DEV_ENV}", file=sys.stderr)
        return 1

    env = read(EXAMPLE)
    dev = read(DEV_ENV)
    taken = [key for key in (*SECRETS, *FROM_DEV) if dev.get(key)]
    env.update({key: dev[key] for key in taken})
    env.update(PILOT)
    env.update(LOCAL)
    # Kept across runs: Postgres sets its password only when the volume is
    # first created, so a new one would lock the app out of its own data, and a
    # new auth secret would sign every teacher out.
    previous = read(OUT) if OUT.exists() else {}
    env["POSTGRES_PASSWORD"] = previous.get("POSTGRES_PASSWORD") or secrets.token_urlsafe(24)
    env["WEBUI_AUTH_SECRET"] = previous.get("WEBUI_AUTH_SECRET") or secrets.token_urlsafe(48)

    placeholders = [k for k, v in env.items() if "replace-with" in v]
    OUT.write_text(
        "# Generated by make_local_env.py -- local rehearsal only. Do not commit.\n"
        + "".join(f"{key}={value}\n" for key, value in env.items()),
        encoding="utf-8",
    )
    print(f"written {OUT.name}: {len(env)} keys")
    print(f"  from .env      : {', '.join(taken)}")
    print(f"  pilot settings : {', '.join(PILOT)}")
    if placeholders:
        print(f"  STILL PLACEHOLDERS (fill them or they will fail): {', '.join(placeholders)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
