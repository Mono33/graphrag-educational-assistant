"""Alembic environment for the WebUI database.

Two things differ from the stock async template, both deliberate.

**The URL comes from the application, not from alembic.ini.**
``aix.webui.db.resolve_db_url()`` is the single place that reads
``WEBUI_DATABASE_URL``, so a deployment migrates the database it is actually
going to connect to. Keeping a second copy in ``alembic.ini`` would be one more
thing to hold in sync, and the failure mode — migrating the wrong database —
is silent.

**``render_as_batch`` is on.**
SQLite cannot ``ALTER`` most things. Batch mode rewrites the table instead, so
the same migration script runs on the SQLite used in development and the
Postgres used in production. Without it, migrations would only be testable on
one of the two, which defeats the point of having them.
"""

import asyncio
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.ext.asyncio import async_engine_from_config

# Importing the model modules registers every table against ``Base.metadata``.
# Autogenerate compares against exactly what is imported here: a model module
# missing from this list is silently invisible, and its table would show up as
# a DROP in the next autogenerated revision.
from aix.api import idempotency as _api_idempotency  # noqa: F401
from aix.webui.auth import models as _auth_models  # noqa: F401
from aix.webui.db import Base, resolve_db_url
from aix.webui.lessons import models as _lesson_models  # noqa: F401
from aix.webui.materials import models as _material_models  # noqa: F401

config = context.config
config.set_main_option("sqlalchemy.url", resolve_db_url())

# Only when alembic owns the process. ``fileConfig`` reconfigures logging
# globally and disables existing loggers, which is what you want from the CLI
# and emphatically not when migrations run embedded in the application at
# startup: it would silence the app's own logging for the rest of the process.
# The injected connection is what distinguishes the two.
if config.config_file_name is not None and config.attributes.get("connection") is None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata


def _configure(connection=None, url=None) -> None:
    """Shared configuration so offline and online modes cannot drift apart."""
    context.configure(
        connection=connection,
        url=url,
        target_metadata=target_metadata,
        render_as_batch=True,
        compare_type=True,
        compare_server_default=True,
        dialect_opts={"paramstyle": "named"},
    )


def run_migrations_offline() -> None:
    """Emit SQL to stdout without a DBAPI connection (``alembic upgrade --sql``).

    Useful for handing a reviewable script to whoever runs the production
    migration, rather than asking them to trust an opaque command.
    """
    _configure(url=config.get_main_option("sqlalchemy.url"))
    with context.begin_transaction():
        context.run_migrations()


def _do_run_migrations(connection) -> None:
    _configure(connection=connection)
    with context.begin_transaction():
        context.run_migrations()


async def _run_async_migrations() -> None:
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    async with connectable.connect() as connection:
        await connection.run_sync(_do_run_migrations)
    await connectable.dispose()


def run_migrations_online() -> None:
    """Migrate, reusing a caller-supplied connection when there is one.

    ``aix.webui.db.init_db`` runs migrations at startup inside a transaction it
    already holds — the one carrying the Postgres advisory lock that stops two
    uvicorn workers migrating at once. It passes that connection in through
    ``config.attributes``; opening a second engine here would escape the lock
    and reintroduce the race the lock exists to prevent.

    With no injected connection (the ``alembic`` CLI) we open our own engine.
    """
    connection = config.attributes.get("connection")
    if connection is not None:
        _do_run_migrations(connection)
        return
    asyncio.run(_run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
